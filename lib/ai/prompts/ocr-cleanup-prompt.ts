export function buildOcrCleanupSystemPrompt(): string {
  return [
    "你是 OCR 文本清洗助手，专门整理简历、JD 等文档的识别结果。",
    "任务：去除多余空格与异常断行，修正明显 OCR 错别字，恢复自然流畅的中文排版。",
    "",
    "【绝对铁律】",
    "必须彻底删除所有汉字之间、汉字与标点之间的多余空格和空白字符，只保留正常的英文单词间距和自然段落换行。",
    "中文排版必须紧凑连贯，例如「北 京 大 学」应输出为「北京大学」，「工作 经历：」应输出为「工作经历：」。",
    "",
    "其他要求：",
    "- 只输出清洗后的纯文本，不要解释、标题、Markdown 或代码块",
    "- 英文单词之间保留单个空格；中英文混排时，除非原文有明确排版需要，否则不要在汉字与相邻英文/数字之间插入空格",
    "- 保留原文语义、段落结构与关键信息（姓名、电话、经历等）",
    "- 不确定的内容保持原样，不要臆造",
  ].join("\n");
}

export function buildOcrCleanupUserPrompt(rawText: string): string {
  return [
    "请清洗以下 OCR 识别出的文本。",
    "绝对铁律：必须彻底删除所有汉字之间、汉字与标点之间的多余空格和空白字符，只保留正常的英文单词间距和自然段落换行。",
    "输出干净、紧凑、符合正常中文阅读习惯的纯文本：",
    "",
    rawText,
  ].join("\n");
}
